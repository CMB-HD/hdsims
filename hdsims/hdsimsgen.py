    def generate_lensed_cmb_sim(self, save_intermediate_maps=False, **kwargs):
        """Generate and save the ultrahigh-resolution lensed CMB 
        simulation.
        
        The lensed CMB simulation is generated by lensing the unlensed
        CMB map(s) by the lensing convergence map.
        
        Parameters
        ----------
        save_intermediate_maps : bool, default=False
            Whether to save the lower-resolution lensing convergence map.
            
        Other Parameters
        ----------------
        **kwargs : dict
            Optional keyword arguments for the lower-resolution, full-sky
            simulations passed to the  `get_intermediate_sim`, 
            `get_intermediate_sim_power`, and
            `get_lowres_sim_component_name` methods.
            
            The other allowed keyword arguments are `cmb_seed` (`int`) and
            `pol` (`bool`). The defaults are given by the corresponding
            attributes defined during initialization.
            
        See Also
        --------
        generate_kappa_sim : Generate the lensing convergence simulation.
        generate_unlensed_cmb_sim : Generate the unlensed CMB simulation.
        generate_hd_sims : 
            Generate simulations for all map components and frequencies.
        """
        t_start = time.time()
        component = 'cmb'
        pol = self.get_kwarg('pol', **kwargs)
        sim_type = 'TQU' if pol else 'T'
        sim_fname = self.get_signal_sim_fname(component, **kwargs)
        if not os.path.exists(sim_fname):
            self.infomsg(f"generating lensed CMB {sim_type} sim")
            
            # load in kappa map and unlensed CMB map, apodize them, 
            # and get their alms:
            window = self.get_apod_window(width=self.padded2x_width, height=self.padded2x_height, 
                                          apod_width=self.map_apod_width, save=True)

            self.infomsg(f"getting the unlensed CMB sim")
            unlensed_cmb_sim = self.generate_unlensed_cmb_sim(return_full_map=True, **kwargs)
            self.infomsg("getting the unlensed CMB alms")
            t = time.time()
            unlensed_cmb_alms = cs.map2alm(unlensed_cmb_sim * window, lmax=self.lmax4alms)
            self.infomsg(f"{utils.tmsg(time.time() - t)} for unlensed CMB alms")

            self.infomsg(f"getting the kappa sim")
            kappa_sim = self.generate_kappa_sim(save_intermediate_maps=save_intermediate_maps, return_full_map=True)
            self.infomsg("getting the kappa alms")
            t = time.time()
            kappa_alms = cs.map2alm(kappa_sim * window, lmax=self.lmax4alms)
            # convert from lensing convergence to lensing potential:
            phi_alms = cs.almxfl(alm=kappa_alms, lfilter=lambda x: 2. / (x * (x + 1)))
            phi_alms[~np.isfinite(phi_alms)] = 0
            self.infomsg(f"{utils.tmsg(time.time() - t)} for kappa alms")

            # lens the unlensed CMB map by the kappa map:
            self.infomsg(f"lensing the unlensed CMB map by the kappa map")
            t = time.time()
            sim = lensing.lens_map_curved(unlensed_cmb_sim.shape, unlensed_cmb_sim.wcs, phi_alms, unlensed_cmb_alms)[0]
            self.infomsg(f"{utils.tmsg(time.time() - t)} to do the lensing")

            # convolve the pixel window and cut out the un-apodized region:
            self.infomsg(f"convolving pixel window and cutting out the"
                         f" inner {self._padded_map_area_info} un-apodized region")
            sim_shape = (3, *self.padded_shape) if (len(sim.shape) > 2) else self.padded_shape
            sim = enmap.project(enmap.apply_window(sim * window), sim_shape, self.padded_wcs)
            enmap.write_map(sim_fname, sim)
            self.infomsg(f"saved lensed CMB {sim_type} sim to {sim_fname}")
        self.infomsg(f"{utils.tmsg(time.time() - t_start)} total for lensed CMB {sim_type} sim")
    
    
