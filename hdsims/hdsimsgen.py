            if full_sim_is_saved: 
                full_sim = enmap.read_map(full_sim_fname)
            else: 
                self.infomsg(f"generating unlensed CMB {sim_type} sim")
                t = time.time()
                theo = self.get_camb_theory()
                seed = self.get_kwarg('cmb_seed', **kwargs)
                full_sim = maps.make_cmb_sim_from_theory(self.padded2x_shape, self.padded2x_wcs, 
                                                         theory_dict=theo, pol=pol, seed=seed)
