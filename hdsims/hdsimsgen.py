"""Generate ultrahigh-resolution simulations from a set of 
lower-resolution, full-sky counterparts.

"""

import os
import time
import camb
import numpy as np
from pixell import enmap, curvedsky as cs, lensing
from . import utils, siminfo as si, maps, fgcatalogs, simutils, s10sims


class HDSimsGen(s10sims.S10Sims):
    """Generate ultrahigh-resolution extragalactic foreground, lensing
    convergence, and CMB simulations on a patch of the sky.
    
    This class will generate and save simulated maps of the tSZ, kSZ, CIB,
    radio galaxies, the lensing convergence, and the unlensed and lensed
    CMB. It will also save catalogs of the CIB and radio galaxies and the
    SZ clusters within the maps, and the theory power spectra used to
    generate the kSZ, lensing convergence, and unlensed CMB maps. The 
    ultrahigh-resolution simulations are generated from a set of full-sky,
    lower-resolution counterparts.
    
    By default (i.e., with all parameters set to their default values),
    this class will generate the simulations used in MacInnis et. al. 2025
    (arXiv:XXXX.XXXX !! TODO !!), which are also available on LAMBDA
    (!! TODO : LINK !!).

    Attributes
    ----------
    components : list of str
    cmb_seed : int
    pol : bool
    lmax4alms, lmax4theo : int
    theo_components : list of str
        A list of map components that have corresponding theory power
        spectra.
    
    Notes
    -----
    Attributes listed above without a description will have the same value
    as the corresponding parameter passed when initializing the class. 
    Inherited attributes are not listed above.
    
    The `components`, `cmb_seed`, and `pol` attributes will be added to
    the dictionary of `default_kwargs` (defined in the 
    `hdsims.simutils.Sims` class).
    
    The maps for each component (and frequency, if applicable) are saved
    on the patch of sky defined by the `padded_width` and `padded_height`
    attributes (see the `hdsims.simutils.Sims` class for more information). 
    We refer to these maps are the 'signal' (or 'signal-only') simulations.
    
    The lensing convergence map is dimensionless, and is not
    convolved with the CAR pixel window function. All other maps have 
    units of uK and have been convolved with the pixel window.
    
    By default (i.e., if the `hdsims` modules have not been modified), 
    the Sehgal et. al. 2010 ('S10', arXiv:0908.0540) simulations are used
    as the initial set of full-sky, lower-resolution simulations. 
    - For the tSZ, kSZ, and lensing convergence maps, we begin with
      the maps at the S10 resolution on the patch of sky, and upgrade
      them to the higher resolution.
      - We fill the small-scale power of the kSZ and lensing convergence
        maps with a Gaussian realization generated from a theory power
        spectrum. The theory curve is obtained by fitting a template power
        spectrum to the large-scale power in the map.
    - The CIB and radio maps are generated at the higher resolution from
      catalogs that were obtained from the corresponding full-sky S10
      catalogs.
    - The unlensed CMB maps are Gaussian realizations generated from CAMB
      theory power spectra that have the cosmology of the S10 simulations
      but calculated using the CMB-HD accuracy settings.
    - The lensed CMB maps are generated by lensing the unlensed CMB maps
      by the lensing convergence maps.
    See arXiv:XXXX.XXXX (!! TODO !!) for more details.
    """
    
    def __init__(self, hd_sims_dir, lowres_sims_dir,
                 freqs=si.freqs, components=si.components,
                 ra_ctr=si.ra_ctr, dec_ctr=si.dec_ctr, width=si.width, height=si.height, 
                 apod_width=si.apod_width, map_apod_width=None, res=si.hd_res,
                 cmb_seed=si.cmb_seed, pol=True, lmax4alms=si.lmax4alms, lmax4theo=si.lmax4theo,
                 verbose=False, log=None, make_output_dirs=True, **kwargs):
        """Initialize the `HDSimsGen` class for a given patch on the sky.
        
        Parameters
        ----------
        hd_sims_dir : str
            The path to the directory where all of the output files will
            be saved. This directory will be created if it does not
            already exist.
        lowres_sims_dir : str
            The path to the directory where the full-sky lower-resolution
            simulations and catalogs have been saved. 
        freqs : list of int, default=[30, 90, 148, 219, 277, 350]
            A list of map frequencies (in GHz). Each frequency in the list
            must be one of `30`, `90`, `148`, `219`, `277`, or `350`.
        components : list of str, optional
            A list of map components to generate. Each component in the
            list must be one of: `'tsz'` for the thermal SZ (tSZ); `'ksz'`
            for the kinetic SZ (kSZ); `'cib'` for the cosmic infrared
            background (CIB); `'radio'` for radio galaxies; and either 
            `'cmb'` or `'unlensed_cmb'` for the lensed or unlensed CMB,
            respectively. If `'cmb'` is in the list, then unlensed CMB and
            lensing convergence (`'kappa'`) simulations will also be 
            generated and saved. By default, the list includes all
            components except the `'unlensed_cmb'`.
        ra_ctr, dec_ctr : int or float, optional
            The right ascension (R.A.) and declination (dec.), in degrees,
            of the center of the patch of sky. The defaults are `ra_ctr=6`
            and `dec_ctr=6`.
        width : int or float, default=10
            The width (in degrees) of the region of the maps to be used
            for analysis, e.g. when taking the power spectrum of the
            simulations. 
        height : int or float, optional
            The height (in degrees) of the region of the maps to be used 
            for analysis. If the `height` is not provided, it is assumed
            to be equal to the `width`.
        apod_width : int or float, default=1
            The width (in degrees) of the region along each edge of the
            map that will be apodized before calculating its power
            spectrum.
        cmb_seed : int, default=58
            The random seed to use when generating a realization of the
            unlensed CMB from a theory power spectra. 
        pol : bool, default=True
            If `pol=True`, CMB temperature and polarization (T, Q, and U)
            maps will be generated. Otherwise, only the temperature map
            will be generated.
        
        Other Parameters
        ----------------
        lmax4alms : int, default=24000
            The maximum multipole to use when taking the spherical
            harmonic transform of a map.
        lmax4theo : int, default=40000
            The maximum multipole of any theory curves used to generate
            the simulations.
        map_apod_width : int or float, optional
            The width (in degrees) of the region along each edge of the 
            map that will be apodized before taking any Fourier or
            spherical harmonic transforms. The default is determined by
            the parent class.
        res : int or float, default=0.04
            The resolution of the maps, in arcminutes. 
        verbose : bool, default=False
            Whether to print messages describing the progress of some
            calculations.
        log : logging.Logger, optional
            A `logging.Logger` instance to use when `verbose=True`. If a
            `log` is passed, any messages will be passed to `log.info`.
            Otherwise, messages will be passed to the `print` function.
        make_output_dirs : bool, default=True
            Whether to create the sub-directories under the `hd_sims_dir`
            where the output files will be saved. This should not be 
            changed, but it is provided to, e.g., allow you to check where
            the files will be saved before generating the simulations.
        **kwargs : dict
            Any keyword arguments that are needed to initialize the parent
            class for the lower-resolution, full-sky simulations.
        """
        components = simutils.validate_sim_component_names(components) 
        freqs = simutils.validate_sim_freqs(freqs)
        super().__init__(hd_sims_dir, lowres_sims_dir, freqs=freqs, components=components, 
                         ra_ctr=ra_ctr, dec_ctr=dec_ctr, width=width, height=height, 
                         apod_width=apod_width, map_apod_width=map_apod_width, res=res,
                         verbose=verbose, log=log, make_output_dirs=make_output_dirs, **kwargs)
        self.components = components.copy()
        self.cmb_seed = cmb_seed
        self.pol = pol
        self.lmax4alms = int(round(lmax4alms))
        self.lmax4theo = int(round(lmax4theo))
        self.theo_components = ['ksz', 'kappa', 'cmb', 'unlensed_cmb']
        self.default_kwargs = {**self.default_kwargs, 'components': self.components, 
                               'cmb_seed': self.cmb_seed, 'pol': self.pol}
        
    
    def get_component_name(self, component, **kwargs):
        """"Return a name used as a label for each map component in file
        names.
        
        Parameters
        ----------
        component : str
            The name of the map component. The allowed values are `'ksz'`,
            `'tsz'`, `'cib'`, `'radio'`, `'kappa'`, `'cmb'`, or 
            `'unlensed_cmb'` for kSZ, tSZ, CIB, radio, lensing
            convergence, lensed CMB, or unlensed CMB, respectively.
            
        Returns
        -------
        component_name : str
            A short name for the map `component` that will be used in file
            names.
        
        Other Parameters
        ----------------
        **kwargs : dict
            Optional keyword arguments passed to the 
            `get_lowres_sim_component_name` method.
        
            If the `component` is `'cmb'` or `'unlensed_cmb'`, you may
            also pass keyword arguments for `cmb_seed` (`int`) and
            `pol` (`bool`). The defaults are given by the corresponding
            attributes, defined during initialization.
        """
        all_components = [*self.lowres_sim_components, 'cmb', 'unlensed_cmb']
        component = simutils.validate_sim_component_name(component, valid_components=all_components)
        if component in self.lowres_sim_components:
            component_name = self.get_lowres_sim_component_name(component, **kwargs)
        elif simutils.has_cmb(component):
            cmb_seed = self.get_kwarg('cmb_seed', **kwargs)
            pol = self.get_kwarg('pol', **kwargs)
            cmb_info = 'TQU' if pol else 'T'
            component_name = f'{component}{cmb_info}{cmb_seed:04d}'
        return component_name
        

    def get_cambparams_for_sim(self):
        """Return a `camb.model.CAMBparams` instance using the cosmology
        of the lower-resolution simulations and the CMB-HD accuracy.
        
        These CAMB parameters are used when calculating the CAMB unlensed
        CMB and lensing convergence theory power spectra that are needed
        to generate the corresponding simulations.
        
        Returns
        -------
        pars : camb.model.CAMBparams
            The instance
        
        See Also
        --------
        get_camb_theory :
            Calculate the CAMB unlensed CMB and lensing convergence power
            spectra.
        get_camb_cosmo_params : Dictionary of CAMB cosmological parameters.
        hdsims.siminfo.hd_camb_accuracy_params :
            Dictionary of CMB-HD CAMB accuracy parameters.
        """
        camb_cosmo_params = self.get_camb_cosmo_params()
        if camb_cosmo_params is None: # use the default cosmology
            pars = simutils.get_cambparams_for_sim(lmax=self.lmax4theo)
        else: # use cosmological params for low-res sims and HD accuracy:
            camb_params_dict = {**camb_cosmo_params, **si.hd_camb_accuracy_params, 'lmax': self.lmax4theo + 500}
            pars = camb.set_params(**camb_params_dict)
        return pars
    

    def get_camb_theory(self):
        """Return a dictionary of unlensed CMB and lensing convergence
        theory power spectra calculated with CAMB.
        
        If the theory has already been calculated and saved, it will be
        loaded instead of re-calculated. Otherwise, it will be calculated
        and saved.
        
        Returns
        -------
        theo : dict of array_like of float
            A dictionary of the theory power spectra with the following
            keys and values:
            - `'ells'`: array of each integer multipole between zero and
                  the maximum given by the `lmax4theo` attribute.
            - `'tt'`, `'te'`, `'ee'`, `'bb'`: unlensed CMB TT, TE, EE, and
                  BB power spectra (in units of uK^2 as C_ell's, i.e. 
                  without any multiplicative multipole factors).
            - `'kk'`: the lensing convergence power spectrum, i.e.
                  C_L^kappakappa = L^2 * (L+1)^2 * C_L^phiphi / 4.
                  
        See Also
        --------
        get_cambparams_for_sim : 
            The `camb.model.CAMBparams` instance used to calculate the
            power spectra.
        get_camb_theory_fname : Path to the theory file.
        hdsims.simutils.calculate_camb_unlensed : Calculate the theory.
        """
        camb_theory_fname = self.get_camb_theory_fname()
        if os.path.exists(camb_theory_fname):
            theo = utils.load_dict_from_file(camb_theory_fname, si.spectra_col_names)
        else:
            if self.get_camb_cosmo_params() is not None: # calculate the theory for the given cosmology:
                pars = self.get_cambparams_for_sim()
                theo = simutils.calculate_camb_unlensed(camb_params=pars, lmax=self.lmax4theo)
            elif self.lmax4theo != si.lmax4theo: # calculate w/ default cosmology but different lmax
                theo = simutils.calculate_camb_unlensed(lmax=self.lmax4theo)
            else: # load the default theory spectra:
                theo = simutils.load_camb_theory()
            header_info = ("unlensed CMB spectra as C_ell (no multiplicative ell-factors) in uK^2;"
                           " lensing convergence spectrum is C_L^kappakappa = [L(L+1)]^2 C_L^phiphi / 4")
            utils.save_dict_to_file(camb_theory_fname, theo, keys=si.spectra_col_names, extra_header_info=header_info)
        return theo
        
    
    def get_camb_theory_fname(self):
        """Return the path to the file where the CAMB unlensed CMB and
        lensing convergence power spectra are saved.
        """
        fname = 'camb_unlensed_cmb_and_clkk_theory.txt'
        return os.path.join(self.sim_dir(), fname)


    def get_sim_theory_fname(self, component):
        """Return the path to the file where the sim theory power spectra
        are saved.
        
        Parameters
        ----------
        component : str
            The name of the map component corresponding to the theory. The
            `component` must be one of `'ksz'`, `'kappa'`, `'cmb'`, or 
            `'unlensed_cmb'`.
        
        Returns
        -------
        fname : str
            The path to the theory file.
        """
        component = simutils.validate_sim_component_name(component, valid_components=self.theo_components)
        if component == 'unlensed_cmb':
            fname = self.get_camb_theory_fname()
        elif 'cmb' in component: # lensed
            fname = os.path.join(self.sim_dir(), 'lensed_cmb_sim_theory.txt')
        else: # ksz, kappa
            fname = os.path.join(self.sim_dir(), f'theory_for_smallscale_{component}.txt')
        return fname
    
    
    def load_sim_theory(self, component):
        """Load the theory power spectra for the simulations.
        
        Parameters
        ----------
        component : str
            The name of the map component corresponding to the theory. The
            `component` must be one of `'ksz'`, `'kappa'`, `'cmb'`, or 
            `'unlensed_cmb'`.
            
        Returns
        -------
        theo : dict of array_like of float
            A dictionary of the theory power spectra. It will always have
            a key  `'ells'` for each integer multipole between zero and
            the maximum given by the `lmax4theo` attribute.
            
            If the `component` is `'cmb'` or `'unlensed_cmb'`, it will
            have keys `'tt'`, `'te'`, `'ee'`, `'bb'` for the CMB TT, TE,
            EE, and BB power spectra (in units of uK^2 as C_ell's, i.e. 
            without any multiplicative multipole factors).
            
            If `component='ksz'`, it will have a key `'tt'` for the kSZ
            power spectrum (in units of uK^2 as C_ell's, i.e. without any
            multiplicative multipole factors).
            
            If `component='kappa'`, it will have a key `'kk'` for the
            lensing convergence power spectrum, 
            C_L^kappakappa = L^2 * (L+1)^2 * C_L^phiphi / 4.
            
        Notes
        -----
        The unlensed CMB theory power spectra are calculated by CAMB and
        used to generate the unlensed CMB simulation. 
        
        The kSZ and lensing convergence theory power spectra are obtained
        by fitting parameters that are used scale a template power
        spectrum. The parameters are fit to the large-scale power spectrum
        of the simulation. On small scales, we use a Gaussian realization
        of the theory kSZ or lensing convergence power spectrum to
        generate the corresponding simulation. The lensing convergence
        template power spectrum is calculated by CAMB, using the same 
        cosmology and accuracy as the unlensed CMB theory. See arXiv:XXXX.XXXXX (!! TODO !!)
        for details about the kSZ template power spectrum.
        
        The lensed CMB theory power spectra are also calculated by CAMB,
        using the same cosmology and accuracy as the unlensed CMB theory,
        but using the measured power spectrum of the lensing convergence
        simulation to do the lensing, as opposed to the CAMB theory 
        lensing spectrum. Unlike the other theory power spectra, the
        lensed CMB theory spectra are not used to generate the lensed CMB
        simulations. This also means that the theory is not calculated
        while generating the lensed CMB simulations.
        
        The kSZ, lensing convergence, and lensed CMB theory power spectra
        are unique to a given patch of sky, while the unlensed CMB power
        spectra are fixed for a given set of cosmological and accuracy 
        parameters.
        """
        component = simutils.validate_sim_component_name(component, valid_components=self.theo_components)
        if simutils.has_cmb(component):
            if 'unlensed' in component:
                theo = utils.load_dict_from_file(self.get_camb_theory_fname(), si.spectra_col_names, skip_cols=['kk'])
            else:
                theo = utils.load_dict_from_file(self.get_sim_theory_fname(component), si.spectra_col_names[:-1])
        else:
            theo = utils.load_dict_from_file(self.get_sim_theory_fname(component), 
                                             simutils.get_spectra_keys(component))
        return theo
    
    
    def get_catalog_fname(self, component, **kwargs):
        """Return the path to the catalog of objects in the simulations
        for a patch of sky.
        
        The area of the patch of sky is the same as the signal-only
        simulations, given by the `padded_width` and `paddd_height`
        attributes.
        
        Parameters
        ----------
        component : str
            The name of the map component. The allowed values are: 
            `'radio'` for radio galaxies, `'cib'` for the CIB, or one of
            `'sz'`, `'tsz'`, or `'ksz'` for SZ clusters.
            
        Returns
        -------
        fname : str
            The path to the catalog file.
            
        Other Parameters
        ----------------
        **kwargs : dict
            Additional keyword arguments passed to the 
            `get_lowres_sim_component_name` method.
            
        See Also
        --------
        get_sim_catalog : 
            The catalog used to generate the CIB and radio simulations.
        """
        catalog_components = ['radio', 'cib', 'tsz', 'ksz', 'sz']
        component = simutils.validate_sim_component_name(component, valid_components=catalog_components)
        component_info = self.get_component_name(component, **kwargs)
        if ('sz' in component) and (component in component_info):
            component_info = component_info.replace(component, 'sz') # one catalog for SZ
        patch_info = f'{simutils.round_str(self.padded_width)}x{simutils.round_str(self.padded_height)}deg'
        fname = os.path.join(self.sim_dir(), f'{component_info}_{patch_info}.csv')
        return fname
    
    
    def get_catalog(self, component, include_padded_area=True, **kwargs):
        """Return the catalog of objects in the simulations for a patch
        of sky.
        
        Parameters
        ----------
        component : str
            The name of the map component. The allowed values are: 
            `'radio'` for radio galaxies, `'cib'` for the CIB, or one of
            `'sz'`, `'tsz'`, or `'ksz'` for SZ clusters.
        include_padded_area : bool, default=True
            If `include_padded_area=True`, the area of the patch of sky is
            the same as the signal-only  simulations, given by the 
            `padded_width` and `paddd_height` attributes. Otherwise, the
            area will be given by the (smaller) `width` and `height` 
            attributes.
            
        Returns
        -------
        catalog : pandas.DataFrame
            A catalog of objects in the simulations of the `component` on
            the given patch of sky. 
            
            The catalog has columns named `'RADeg'` and `'decDeg'` for the
            R.A. and dec. coordinates (in degrees), respectively, of each
            object. For CIB and radio galaxies, the columns for the flux
            (in mJy) of each source at 30, 90, 148, 219, 277, and 350 GHz
            are named `'fluxmJy_{freq}GHz'` (e.g., the column name for 
            90 GHz is `'fluxmJy_90GHz'`).
            
        Other Parameters
        ----------------
        **kwargs : dict
            Additional keyword arguments passed to the 
            `get_lowres_sim_component_name` method.
            
        See Also
        --------
        get_sim_catalog : 
            The catalog used to generate the CIB and radio simulations.
        """
        # get the catalog for the larger patch of sky:
        fname = self.get_catalog_fname(component, **kwargs)
        if os.path.exists(fname):
            catalog = fgcatalogs.load_catalog(fname)
        else:
            # load the catalog used to generate the simulations, remove
            # rows with coordinates located outside the area of the 
            # signal-only maps, and save it:
            full_catalog = self.get_sim_catalog(component, **kwargs)
            catalog = fgcatalogs.trim_catalog_positions(full_catalog, ra_ctr=self.ra_ctr, dec_ctr=self.dec_ctr,
                                                        width=self.padded_width, height=self.padded_height)
            catalog.to_csv(fname)
            self.infomsg(f'saved {fname}')
        if not include_padded_area:
            # remove rows with coordinates located outside of the inner
            # `width` x `height` region:
            catalog = fgcatalogs.trim_catalog_positions(catalog, ra_ctr=self.ra_ctr, dec_ctr=self.dec_ctr, 
                                                        width=self.width, height=self.height)
        return catalog
    
    
    def get_signal_sim_fname(self, component, freq=None, trim_map=True, unlensed_cmb_pixwin=True, **kwargs):
        """Return the path to the ultrahigh-resolution signal-only 
        simulation.
        
        Parameters
        ----------
        component : str
            The name of the map component. The allowed values are `'tsz'`,
            `'ksz'`, `'cib'`, `'radio'`, `'kappa'`, `'cmb'`, or 
            `'unlensed_cmb'` for the tSZ, kSZ, CIB, radio, lensing 
            convergence, lensed CMB, or unlensed CMB map(s), respectively.
        freq : int or None, default=None
            The map frequency (in GHz). If the `component` is `'tsz'`,
            `'cib'`, or `'radio'`, the frequency must be `30`, `90`, 
            `148`, `219`, `277`, or `350`. Otherwise, the `freq` is not 
            used.
        
        Returns
        -------
        fname : str
            The path to the signal-only map.
        
        Other Parameters
        ----------------
        trim_map : bool, default=True
            Only used if the `component` is `'kappa'` or `'unlensed_cmb'`.
            If `trim_map=False`, returns the path to the map on the 
            initial, larger patch of sky with area given by the 
            `padded2x_width` and `padded2x_height` attributes. By default,
            these maps are not saved.
        unlensed_cmb_pixwin : bool, default=True
            Only used if `component='unlensed_cmb'`. 
            If `unlensed_cmb_pixwin=False`, returns the path to the
            unlensed CMB simulation that has not been convolved with the 
            pixel window. By default, this map is not saved.
        **kwargs : dict
            Additional keyword arguments passed to the 
            `get_component_name` method.
        """
        component = simutils.validate_sim_component_name(component)
        fname_info = []
        # add info about the component, and freq if necessary:
        if simutils.has_freq_dependent_component(component):
            freq = simutils.validate_sim_freq(freq)
            fname_info.append(f'{freq:03d}')
        fname_info.append(self.get_component_name(component, **kwargs))
        # add info about pixel window (unlensed CMB is initially saved without a pixel window):
        if simutils.has_pixwin(component) or ((component == 'unlensed_cmb') and unlensed_cmb_pixwin):
            fname_info.append('pixwin')
        # add info about size of map (unlensed CMB & kappa are initially saved on larger patch of sky):
        if (component.lower() in ['kappa', 'unlensed_cmb']) and (not trim_map):
            width = self.padded2x_width
            height = self.padded2x_height
        else:
            width = self.padded_width
            height = self.padded_height
        fname_info.append(f'{simutils.round_str(width)}x{simutils.round_str(height)}deg')
        # make the file name:
        fname_root = '_'.join(fname_info)
        fname = os.path.join(self.sim_dir(), f'{fname_root}.fits')
        return fname
    
    
    def _load_cmb_signal_sim(self, component, trim_map=True, unlensed_cmb_pixwin=True, **kwargs):
        """Load the signal-only lensed or unlensed CMB map(s).
        
        Parameters
        ----------
        component : str
            Must be either `'cmb'` or `'unlensed_cmb'` for the lensed or
            unlensed CMB, respectively.
            
        Returns
        -------
        sim : pixell.enmap.ndmap
            The CMB map(s). If `pol=True`, the temperature and 
            polarization (T, Q, and U) maps are returned, and the `shape`
            of the `sim` is `(3, Ny, Nx)`, where `(Ny, Nx)` is the shape 
            of an individual T, Q, or U map (`sim[0]`, `sim[1]`, and 
            `sim[2]`, respectively). Otherwise, only the temperature map
            is returned.
        
        Other Parameters
        ----------------
        trim_map : bool, default=True
            Only used if `component='unlensed_cmb'`. If `trim_map=False`,
            returns the map on the initial, larger patch of sky with area
            given by the `padded2x_width` and `padded2x_height`
            attributes. By default, these maps are not saved.
        unlensed_cmb_pixwin : bool, default=True
            Only used if `component='unlensed_cmb'`. 
            If `unlensed_cmb_pixwin=False`, returns the unlensed CMB map
            that has not been convolved with the pixel window function.
            By default, this map is not saved. The lensed CMB simulation
            is always convolved with the pixel window.
        **kwargs : dict
            The allowed keyword arguments are `cmb_seed` (`int`) and
            `pol` (`bool`). The defaults are given by the corresponding
            attributes defined during initialization.
        """
        # in some cases (e.g., if the TQU sim was saved and `pol=False`), 
        # we will get a `FileNotFoundError` if we just try to load the 
        # file name returned by `get_signal_sim_fname`; to avoid needing 
        # to save a new (e.g., T-only) copy of the map, we try to load a
        # different map here (e.g., the TQU map) and return the version of
        # it that we actually want.
        pol = self.get_kwarg('pol', **kwargs)
        fname = self.get_signal_sim_fname(component, trim_map=trim_map, 
                                          unlensed_cmb_pixwin=unlensed_cmb_pixwin, **kwargs)
        
        if (not os.path.exists(fname)) and (not pol):
            # check if the TQU map was saved; if it was, load it and
            # return only the T component:
            kwargs_with_pol = {**kwargs, 'pol': True}
            fname_with_pol = self.get_signal_sim_fname(component, trim_map=trim_map, 
                                                       unlensed_cmb_pixwin=unlensed_cmb_pixwin, **kwargs_with_pol)
            if os.path.exists(fname_with_pol):
                sim = enmap.read_map(fname_with_pol)[0]
                return sim

        if (not os.path.exists(fname)) and ('unlensed' in component) and (trim_map or unlensed_cmb_pixwin):
            # check if the unlensed CMB map is saved on the initial,
            # larger patch of sky and without a pixel window:
            orig_fname = self.get_signal_sim_fname(component, trim_map=False, unlensed_cmb_pixwin=False, **kwargs)
            if os.path.exists(orig_fname):
                sim = enmap.read_map(orig_fname)
                if unlensed_cmb_pixwin:
                    sim = self.convolve_pixwin(sim)
                if trim_map:
                    sim = enmap.project(sim, self.padded_shape, self.padded_wcs)
                return sim
            elif not pol:
                # check if the TQU map was saved; if it was, load it and 
                # return only the T component:
                kwargs_with_pol = {**kwargs, 'pol': True}
                fname_with_pol = self.get_signal_sim_fname(component, trim_map=False, 
                                                           unlensed_cmb_pixwin=False, **kwargs_with_pol)
                if os.path.exists(fname_with_pol):
                    sim = enmap.read_map(fname_with_pol)[0]
                    if unlensed_cmb_pixwin:
                        sim = self.convolve_pixwin(sim)
                    if trim_map:
                        sim = enmap.project(sim, self.padded_shape, self.padded_wcs)
                    return sim

        # now just try to load the file ; 
        # if it doesn't exist, `FileNotFoundError` will be raised:
        sim = enmap.read_map(fname)
        return sim


