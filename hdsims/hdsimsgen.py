    def generate_ksz_sim(self, save_intermediate_maps=False, **kwargs):
        """Generate and save the ultrahigh-resolution kSZ simulation, and 
        the corresponding catalog of SZ clusters and theory power spectrum.
        
        The kSZ simulation is generated by upgrading the corresponding
        lower-resolution map; on small scales, it is generated from a 
        Gaussian realization from a theory curve that was fit to the 
        large-scale power.
        
        Parameters
        ----------
        save_intermediate_maps : bool, default=False
            Whether to save the corresponding lower-resolution map.
        
        Other Parameters
        ----------------
        **kwargs : dict
            Optional keyword arguments for the lower-resolution, full-sky
            simulations; passed to the `get_intermediate_sim`, 
            `get_intermediate_sim_power`, `get_sim_catalog`, and
            `get_lowres_sim_component_name` methods.
        
        See Also
        --------
        get_intermediate_sim : The corresponding lower-resolution map.
        get_catalog : The catalog of SZ clusters in the simulations.
        get_sim_smallscale_theory : 
            The theory power spectrum for the kSZ sim.
        generate_hd_sims : 
            Generate simulations for all map components and frequencies.
        """
        t_start = time.time()
        component = 'ksz'
        sim_fname = self.get_signal_sim_fname(component, **kwargs)
        if not os.path.exists(sim_fname):
            self.infomsg(f"generating {component} sim")
            # cut out patch from full-sky lower-resolution sim, 
            # apodize it, and upgrade to the higher resolution:
            upgraded_sim = self.upgrade_intermediate_map_resolution(component, 
                                                                    save_intermediate_maps=save_intermediate_maps, 
                                                                    **kwargs)
            # fit amplitude and slope parameters for a theory power 
            # spectrum template that matches the large-scale power 
            # spectrum of the simulation:
            theo_ells, theo_cls = self.get_sim_smallscale_theory(component, 
                                                                 save_intermediate_maps=save_intermediate_maps, 
                                                                 **kwargs)
            # replace the small-scale power in the sim with 
            # a gaussian realization of the theory power spectrum:
            self.infomsg(f"filling in small-scale {component} sim power with a realization from "
                         "a theory spectrum that was fit to the large-scale sim power")
            sim = maps.replace_power_in_map_with_theory(upgraded_sim, theo_cls, self.lmax4alms, 
                                                        seed_for_alms=si.smallscale_alms_seed, 
                                                        lmin_to_replace=si.lmin_for_smallscale_alms[component])
            # convolve the pixel window and 
            # cut out the inner un-apodized region:
            self.infomsg("convolving pixel window and cutting out"
                         f" the inner {self._padded_map_area_info} un-apodized region")
            sim = self.convolve_pixwin(sim, save_apod_window=True)
            sim = enmap.project(sim, self.padded_shape, self.padded_wcs)
            enmap.write_map(sim_fname, sim)
            self.infomsg(f"saved {component} sim to {sim_fname}")
        # also make sure the corresponding SZ catalog is saved:
        self.get_catalog(component, **kwargs)
        self.infomsg(f"{utils.tmsg(time.time() - t_start)} total for {component} sim")
    
    
